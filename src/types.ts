export interface Env {
  DB: D1Database;
  AUDIO_BUCKET?: R2Bucket;
  ASSETS?: Fetcher;
  /** Required for signing/verifying session tokens & OTP hashes. Missing => auth fails closed. */
  JWT_SECRET?: string;
  /** Resend API key configured via `wrangler secret put RESEND_API_KEY`. */
  RESEND_API_KEY?: string;
  /** Sender identity for Resend transactional emails (verified domain). */
  EMAIL_FROM?: string;
  /** Comma-separated whitelist of administrator email addresses. */
  ADMIN_EMAILS?: string;
  ENVIRONMENT: string;
}

